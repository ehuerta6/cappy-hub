function run(command, args, options = {}) {
  const result = spawnSync(command, args, {
    cwd: process.cwd(),
    encoding: "utf8",
    stdio: options.capture ? "pipe" : "inherit",
    input: options.input,
  });

  if (result.error) throw result.error;
  if (result.status !== 0) {
    const output = [result.stdout, result.stderr].filter(Boolean).join("\n");
    throw new Error(
      `${command} ${args.join(" ")} failed with exit code ${result.status}${
        output ? `\n${output}` : ""
      }`,
    );
  }

  return result.stdout ?? "";
}

function parseEnv(output) {
  const values = {};
  for (const line of output.split(/\r?\n/)) {
    const match = line.match(/^([A-Z0-9_]+)=(?:"(.*)"|(.*))$/);
    if (!match) continue;
    values[match[1]] = match[2] ?? match[3] ?? "";
  }
  return values;
}

async function updateLocalEnv(apiUrl, publishableKey) {
  const path = ".env.local";
  let current = "";
  try {
    current = await readFile(path, "utf8");
  } catch {}

  const kept = current
    .split(/\r?\n/)
    .filter(
      (line) =>
        !line.startsWith("NEXT_PUBLIC_SUPABASE_URL=") &&
        !line.startsWith("NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY=") &&
        !line.startsWith("# Generated by npm run local:reset"),
    )
    .join("\n")
    .trim();

  const generated = [
    "# Generated by npm run local:reset",
    `NEXT_PUBLIC_SUPABASE_URL=${apiUrl}`,
    `NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY=${publishableKey}`,
  ].join("\n");

  await writeFile(path, `${generated}\n${kept ? `\n${kept}\n` : ""}`, "utf8");
}

