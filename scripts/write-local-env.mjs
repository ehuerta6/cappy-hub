import { chmod, readFile, writeFile } from "node:fs/promises";
import { spawnSync } from "node:child_process";

const result = spawnSync(
  "node_modules/.bin/supabase",
  ["status", "--output", "env"],
  { encoding: "utf8", stdio: ["ignore", "pipe", "inherit"] },
);
if (result.error) throw result.error;
if (result.status !== 0)
  throw new Error(
    "Could not read local Supabase configuration; start it first.",
  );

const env = {};
for (const line of result.stdout.split(/\r?\n/)) {
  const match = line.match(/^([A-Z0-9_]+)=(?:"(.*)"|(.*))$/);
  if (match) env[match[1]] = match[2] ?? match[3] ?? "";
}

const apiUrl = env.API_URL ?? env.SUPABASE_URL;
const publishableKey = env.PUBLISHABLE_KEY ?? env.ANON_KEY ?? env.ANON_KEY_V2;
const secretKey =
  env.SERVICE_ROLE_KEY ?? env.SECRET_KEY ?? env.SUPABASE_SECRET_KEY;
if (
  !apiUrl ||
  !["http://127.0.0.1:54321", "http://localhost:54321"].includes(apiUrl) ||
  !publishableKey ||
  !secretKey
)
  throw new Error("Local Supabase configuration is incomplete or non-local.");

const path = ".env.local";
let current = "";
try {
  current = await readFile(path, "utf8");
} catch {}
const kept = current
  .split(/\r?\n/)
  .filter(
    (line) =>
      !line.startsWith("NEXT_PUBLIC_SUPABASE_URL=") &&
      !line.startsWith("NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY=") &&
      !line.startsWith("SUPABASE_SECRET_KEY=") &&
      !line.startsWith("# Generated by npm run local:reset"),
  )
  .join("\n")
  .trim();
const generated = [
  "# Generated by npm run local:env",
  `NEXT_PUBLIC_SUPABASE_URL=${apiUrl}`,
  `NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY=${publishableKey}`,
  `SUPABASE_SECRET_KEY=${secretKey}`,
].join("\n");

await writeFile(path, `${generated}\n${kept ? `\n${kept}\n` : ""}`, {
  encoding: "utf8",
  mode: 0o600,
});
await chmod(path, 0o600);
console.log("Local .env.local updated with private file permissions.");
