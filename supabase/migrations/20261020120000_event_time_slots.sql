create function private.assert_event_time_slots(p_event_id bigint,p_starts_at timestamptz default null,
  p_ends_at timestamptz default null,p_event_type_id bigint default null)
returns void language plpgsql security definer set search_path = '' as $$
declare e public.events%rowtype; starts_value timestamptz; ends_value timestamptz; type_value bigint;
begin
  select * into e from public.events where id=p_event_id;
  if not found then raise exception 'Event not found'; end if;
  starts_value:=coalesce(p_starts_at,e.starts_at);
  ends_value:=coalesce(p_ends_at,e.ends_at);
  type_value:=coalesce(p_event_type_id,e.event_type_id);
  if exists(select 1 from public.event_time_slots where event_id=p_event_id) then
    if private.is_session_event_type(type_value) then
      raise exception 'Time Slots are unavailable for Session Events';
    end if;
    if exists(select 1 from public.presentation_slots ps where ps.event_id=p_event_id) then
      raise exception 'This Event has Presenter Slots and cannot use volunteer Time Slots';
    end if;
    if exists(select 1 from public.event_time_slots s where s.event_id=p_event_id
        and (s.starts_at<starts_value or s.ends_at>ends_value)) then
      raise exception 'Time Slots must stay within the Event start and end times';
    end if;
    if exists(select 1 from public.event_time_slots s1 join public.event_time_slots s2
        on s2.event_id=s1.event_id and (s2.starts_at,s2.id)>(s1.starts_at,s1.id)
        and s2.starts_at<s1.ends_at where s1.event_id=p_event_id) then
      raise exception 'Time Slots cannot overlap';
    end if;
  end if;
end;
$$;
revoke all on function private.assert_event_time_slots(bigint,timestamptz,timestamptz,bigint)
  from public,anon,authenticated;

create or replace function private.assert_session_presenter_slots()
returns trigger language plpgsql set search_path = '' as $$
begin
  if not private.is_session_event_type((select event_type_id from public.events where id=new.event_id)) then
    raise exception 'Presenter slots are only allowed for Session Events';
  end if;
  if exists(select 1 from public.event_time_slots where event_id=new.event_id) then
    raise exception 'This Event has volunteer Time Slots and cannot use Presenter Slots';
  end if;
  return new;
end;
$$;

create function private.prevent_event_time_slot_schedule_break()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  if (old.starts_at is distinct from new.starts_at or old.ends_at is distinct from new.ends_at
      or old.event_type_id is distinct from new.event_type_id)
     and exists(select 1 from public.event_time_slots s where s.event_id=old.id) then
    perform private.assert_event_time_slots(new.id,new.starts_at,new.ends_at,new.event_type_id);
  end if;
  if old.event_type_id is distinct from new.event_type_id and
    exists(select 1 from public.event_time_slots s where s.event_id=old.id)
    and private.is_session_event_type(new.event_type_id) then
    raise exception 'Remove volunteer Time Slots before changing this Event to Session type';
  end if;
  return new;
end;
$$;
revoke all on function private.prevent_event_time_slot_schedule_break() from public,anon,authenticated;
create trigger events_keep_time_slots_valid before update of starts_at,ends_at,event_type_id
  on public.events for each row execute function private.prevent_event_time_slot_schedule_break();

-- Per-slot capacity is serialized on the Event row. RLS and revoked table
-- writes keep all assignment changes on the authorized RPC paths below.
create function private.guard_event_time_slot_assignment()
returns trigger language plpgsql security definer set search_path = '' as $$
declare e public.events%rowtype; s public.event_time_slots%rowtype; existing_count bigint;
begin
  if tg_op='UPDATE' and new.event_id=old.event_id and new.slot_id=old.slot_id and
      new.officer_id=old.officer_id then return new; end if;
  select * into e from public.events where id=new.event_id for update;
  if not found then raise exception 'Event not found'; end if;
  select * into s from public.event_time_slots where id=new.slot_id and event_id=new.event_id for update;
  if not found then raise exception 'Time Slot does not belong to this Event'; end if;
  perform private.assert_event_time_slots(e.id);
  existing_count:=(select count(*) from public.event_time_slot_officers x
    where x.slot_id=new.slot_id and (tg_op<>'UPDATE' or x.officer_id<>old.officer_id));
  if s.capacity is not null and existing_count>=s.capacity then
    raise exception 'This Time Slot is full';
  end if;
  return new;
end;
$$;
revoke all on function private.guard_event_time_slot_assignment() from public,anon,authenticated;
create trigger event_time_slot_officers_capacity_guard before insert or update
  on public.event_time_slot_officers for each row execute function private.guard_event_time_slot_assignment();

