create function private.create_recurring_event_with_capacity_and_time_slots(
  p_name text,p_description text,p_event_type_id bigint,p_location text,p_branch_ids bigint[],
  p_slides_url text,p_meeting_notes_url text,p_signup_sheet_url text,p_max_volunteers integer,
  p_request_key uuid,p_recurrence_rule text,p_event_dates date[],p_starts_at timestamptz[],p_ends_at timestamptz[],
  p_time_slots jsonb
) returns bigint language plpgsql security definer set search_path = '' as $$
declare first_id bigint; series_id bigint; prior_slots jsonb;
  had_request boolean:=false;
begin
  perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended(p_request_key::text,73));
  select time_slots,first_event_id into prior_slots,first_id from private.recurring_event_time_slot_requests
    where request_key=p_request_key for update;
  had_request:=found;
  if had_request and prior_slots is distinct from p_time_slots then raise exception 'Idempotency key already used'; end if;
  first_id:=private.create_recurring_event_with_capacity(p_name,p_description,p_event_type_id,p_location,
    p_branch_ids,p_slides_url,p_meeting_notes_url,p_signup_sheet_url,p_max_volunteers,p_request_key,
    p_recurrence_rule,p_event_dates,p_starts_at,p_ends_at);
  select recurrence_series_id into series_id from public.events where id=first_id;
  if not had_request then
    insert into private.recurring_event_time_slot_requests(request_key,time_slots,first_event_id)
      values(p_request_key,p_time_slots,first_id);
  end if;
  for first_id in select id from public.events where recurrence_series_id=series_id order by recurrence_key loop
    perform private.replace_event_time_slots(first_id,p_time_slots,null,null,null,null,true);
  end loop;
  select id into first_id from public.events where recurrence_series_id=series_id order by recurrence_key limit 1;
  return first_id;
