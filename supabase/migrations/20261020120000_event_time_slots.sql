create function private.bulk_add_event_officers_compatible(p_event_id bigint,p_officer_ids bigint[])
returns jsonb language plpgsql security definer set search_path = '' as $$
declare e public.events%rowtype;
begin
  if private.current_active_officer_id() is null then raise exception 'Unauthorized'; end if;
  if not private.can_manage_event(p_event_id) then raise exception 'Event outside branch scope'; end if;
  select * into e from public.events where id=p_event_id;
  if not found then raise exception 'Event not found'; end if;
  if exists(select 1 from public.event_time_slots where event_id=p_event_id) then
    raise exception 'Select Time Slots when adding Officers to this Event';
  end if;
  if e.ends_at<=pg_catalog.now() and exists(
    select 1 from unnest(coalesce(p_officer_ids,'{}'::bigint[])) requested(officer_id)
      join public.point_transactions p on p.officer_id=requested.officer_id and p.event_id=p_event_id
    where p.award_type='manual' and p.removed_at is null
  ) then
    raise exception 'This Officer already has an active award for this Event.';
  end if;
  return private.bulk_add_event_officers(p_event_id,p_officer_ids);
end;
$$;
