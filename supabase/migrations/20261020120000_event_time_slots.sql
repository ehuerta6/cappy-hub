-- Optional volunteer time slots. Each occurrence owns its slot records and
-- assignments; slot participation awards retain the slot identity.
create table public.event_time_slots (
  id bigint generated by default as identity primary key,
  event_id bigint not null references public.events(id) on delete restrict,
  starts_at timestamptz not null,
  ends_at timestamptz not null,
  capacity integer,
  created_at timestamptz not null default pg_catalog.now(),
  created_by uuid references auth.users(id),
  constraint event_time_slots_id_event_key unique (id,event_id),
  constraint event_time_slots_duration_check check (ends_at>starts_at),
  constraint event_time_slots_capacity_check check (capacity is null or capacity>0)
);
create index event_time_slots_event_id_idx on public.event_time_slots(event_id,starts_at,id);

create table public.event_time_slot_officers (
  event_id bigint not null,
  slot_id bigint not null,
  officer_id bigint not null,
  created_at timestamptz not null default pg_catalog.now(),
  created_by uuid references auth.users(id),
  primary key (slot_id,officer_id),
  constraint event_time_slot_officers_slot_fkey foreign key (slot_id,event_id)
    references public.event_time_slots(id,event_id) on delete restrict,
  constraint event_time_slot_officers_signup_fkey foreign key (event_id,officer_id)
    references public.event_officers(event_id,officer_id) on delete cascade,
  constraint event_time_slot_officers_officer_id_fkey foreign key (officer_id)
    references public.officers(id) on delete cascade
);
create index event_time_slot_officers_event_officer_idx
  on public.event_time_slot_officers(event_id,officer_id);

