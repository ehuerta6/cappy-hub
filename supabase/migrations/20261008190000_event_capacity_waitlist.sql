  add column max_volunteers integer check (max_volunteers is null or max_volunteers > 0);

create table public.event_waitlist (
  id bigint generated by default as identity primary key,
  event_id bigint not null references public.events(id) on delete cascade,
  officer_id bigint not null references public.officers(id) on delete cascade,
  joined_at timestamptz not null default pg_catalog.clock_timestamp(),
  unique (event_id, officer_id)
);
create index event_waitlist_fifo_idx on public.event_waitlist(event_id, joined_at, id);
alter table public.event_waitlist enable row level security;
revoke all on public.event_waitlist from public, anon, authenticated;
grant select on public.event_waitlist to authenticated;
grant execute on function private.can_manage_event(bigint) to authenticated;
create policy "Officers read own waitlist entries and managers read queue"
  on public.event_waitlist for select to authenticated
  using (
    officer_id = (select private.current_active_officer_id())
    or private.can_manage_event(event_id)
  );

-- Public reads return counts only. Waitlist identities remain visible only to
