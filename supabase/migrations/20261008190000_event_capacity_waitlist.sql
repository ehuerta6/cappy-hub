create function private.prevent_event_signup_overlap()
returns trigger language plpgsql security definer set search_path = '' as $$
declare capacity integer; confirmed_count bigint; officer_active boolean;
begin
  if tg_table_name = 'event_officers' then
    if tg_op='UPDATE' and new.event_id=old.event_id and new.officer_id=old.officer_id then
      return new;
    end if;
    select max_volunteers into capacity from public.events where id=new.event_id for update;
    if not found then raise exception 'Event not found'; end if;
    confirmed_count := (select count(*) from public.event_officers eo where eo.event_id=new.event_id);
    if capacity is not null and confirmed_count>=capacity then
      raise exception 'Event capacity has been reached';
    end if;
    if exists(select 1 from public.event_waitlist w
      where w.event_id=new.event_id and w.officer_id=new.officer_id) then
      raise exception 'Officer is already on this Event waitlist';
    end if;
  else
    select max_volunteers into capacity from public.events where id=new.event_id for update;
    if not found then raise exception 'Event not found'; end if;
    if capacity is null then raise exception 'Unlimited Events cannot have a waitlist'; end if;
    confirmed_count := (select count(*) from public.event_officers eo where eo.event_id=new.event_id);
    if confirmed_count<capacity then raise exception 'Event still has confirmed capacity'; end if;
    select status='active' into officer_active from public.officers where id=new.officer_id for share;
    if not coalesce(officer_active,false) then raise exception 'Target officer is not active'; end if;
    if exists(select 1 from public.event_officers eo
      where eo.event_id=new.event_id and eo.officer_id=new.officer_id) then
      raise exception 'Officer is already confirmed for this Event';
    end if;
  end if;
  return new;
end;
$$;
create trigger event_officers_no_waitlist_overlap
  before insert or update of event_id, officer_id on public.event_officers
  for each row execute function private.prevent_event_signup_overlap();
create trigger event_waitlist_no_confirmed_overlap
  before insert or update of event_id, officer_id on public.event_waitlist
  for each row execute function private.prevent_event_signup_overlap();
revoke all on function private.prevent_event_signup_overlap() from public, anon, authenticated;

create function private.promote_event_waitlist(p_event_id bigint)
returns integer language plpgsql security definer set search_path = '' as $$
declare event_row public.events%rowtype; candidate record; candidate_active boolean;
  confirmed_count bigint; promoted integer := 0;
begin
  select * into event_row from public.events where id=p_event_id for update;
  if not found then raise exception 'Event not found'; end if;
  confirmed_count := (select count(*) from public.event_officers where event_id=p_event_id);
  for candidate in select w.id,w.officer_id,w.joined_at from public.event_waitlist w
    where w.event_id=p_event_id order by w.joined_at,w.id
  loop
    select status='active' into candidate_active from public.officers
      where id=candidate.officer_id for share;
    if not coalesce(candidate_active,false) then
      delete from public.event_waitlist where id=candidate.id;
    elsif event_row.max_volunteers is null or confirmed_count < event_row.max_volunteers then
      delete from public.event_waitlist where id=candidate.id;
      insert into public.event_officers(event_id,officer_id)
        values(p_event_id,candidate.officer_id);
      confirmed_count := confirmed_count + 1;
      promoted := promoted + 1;
      perform private.write_audit_log('event.waitlist_promoted','event',p_event_id::text,
        pg_catalog.jsonb_build_object('event_id',p_event_id,'officer_id',candidate.officer_id,
          'waitlist_id',candidate.id,'joined_at',candidate.joined_at));
    end if;
  end loop;
  return promoted;
end;
$$;
revoke all on function private.promote_event_waitlist(bigint) from public, anon, authenticated;

create function private.set_event_capacity(p_event_id bigint,p_max_volunteers integer)
returns void language plpgsql security definer set search_path = '' as $$
declare event_row public.events%rowtype; confirmed_count bigint;
begin
  if private.current_active_officer_id() is null then raise exception 'Unauthorized'; end if;
  if p_max_volunteers is not null and p_max_volunteers <= 0 then
    raise exception 'Max volunteers must be a positive whole number';
  end if;
  select * into event_row from public.events where id=p_event_id for update;
  if not found then raise exception 'Event not found'; end if;
  if not private.can_manage_event(p_event_id) then raise exception 'Event outside branch scope'; end if;
  confirmed_count := (select count(*) from public.event_officers where event_id=p_event_id);
  if p_max_volunteers is not null and p_max_volunteers < confirmed_count then
    raise exception 'Max volunteers cannot be lower than the confirmed signup count';
  end if;
  if event_row.max_volunteers is distinct from p_max_volunteers then
    update public.events set max_volunteers=p_max_volunteers where id=p_event_id;
    perform private.write_audit_log('event.capacity_changed','event',p_event_id::text,
      pg_catalog.jsonb_build_object('event_id',p_event_id,'before',
        pg_catalog.jsonb_build_object('max_volunteers',event_row.max_volunteers),
        'after',pg_catalog.jsonb_build_object('max_volunteers',p_max_volunteers)));
  end if;
  perform private.promote_event_waitlist(p_event_id);
end;
$$;
revoke all on function private.set_event_capacity(bigint,integer) from public, anon, authenticated;

create or replace function private.change_event_signup(
  p_event_id bigint,p_officer_id bigint,p_remove boolean
) returns void language plpgsql security definer set search_path = '' as $$
declare current_event public.events%rowtype; actor_id bigint := private.current_active_officer_id();
  changed_rows integer; confirmed_count bigint; waitlist_id bigint;
begin
  if actor_id is null then raise exception 'Unauthorized'; end if;
  select * into current_event from public.events where id=p_event_id for update;
  if not found then raise exception 'Event not found'; end if;
  if current_event.deleted_at is not null or current_event.status='cancelled' or
    current_event.participation_points_per_hour_at_end is not null or current_event.ends_at<=pg_catalog.now() then
    raise exception 'Signups are closed for this event'; end if;
  if p_officer_id is distinct from actor_id and not private.can_manage_event(p_event_id) then
    raise exception 'Cannot manage another officer signup for this event'; end if;
  perform 1 from public.officers where id=p_officer_id and status='active' for share;
  if not found then raise exception 'Target officer is not active'; end if;
  if p_remove then
    delete from public.event_officers where event_id=p_event_id and officer_id=p_officer_id;
    get diagnostics changed_rows=row_count;
    if changed_rows>0 then perform private.promote_event_waitlist(p_event_id); end if;
  elsif exists(select 1 from public.event_officers where event_id=p_event_id and officer_id=p_officer_id) then
    changed_rows := 0;
  else
    confirmed_count := (select count(*) from public.event_officers where event_id=p_event_id);
    if current_event.max_volunteers is not null and confirmed_count>=current_event.max_volunteers then
      insert into public.event_waitlist(event_id,officer_id) values(p_event_id,p_officer_id)
        on conflict(event_id,officer_id) do nothing returning id into waitlist_id;
      get diagnostics changed_rows=row_count;
      if changed_rows>0 then perform private.write_audit_log('event.waitlist_joined','event',p_event_id::text,
        pg_catalog.jsonb_build_object('event_id',p_event_id,'officer_id',p_officer_id,
          'waitlist_id',waitlist_id,'joined_at',(select joined_at from public.event_waitlist where id=waitlist_id))); end if;
      return;
    end if;
    insert into public.event_officers(event_id,officer_id) values(p_event_id,p_officer_id)
      on conflict(event_id,officer_id) do nothing;
    get diagnostics changed_rows=row_count;
  end if;
  if changed_rows>0 then
    perform private.write_audit_log(case when p_remove and p_officer_id=actor_id then 'event.signout'
      when p_remove then 'event.officer_removed' when p_officer_id=actor_id then 'event.signup'
      else 'event.officer_assigned' end,'event',p_event_id::text,
      pg_catalog.jsonb_build_object('officer_id',p_officer_id,'actor_id',actor_id,'removed',p_remove));
  end if;
end;
$$;

create function private.leave_event_waitlist(p_event_id bigint,p_officer_id bigint)
returns void language plpgsql security definer set search_path = '' as $$
declare event_row public.events%rowtype; actor_id bigint := private.current_active_officer_id();
  old_entry public.event_waitlist%rowtype;
begin
  if actor_id is null then raise exception 'Unauthorized'; end if;
  select * into event_row from public.events where id=p_event_id for update;
  if not found then raise exception 'Event not found'; end if;
  if event_row.deleted_at is not null or event_row.status='cancelled' or
    event_row.participation_points_per_hour_at_end is not null or event_row.ends_at<=pg_catalog.now() then
    raise exception 'Waitlist is closed for this event'; end if;
  if p_officer_id is distinct from actor_id and not private.can_manage_event(p_event_id) then
    raise exception 'Cannot manage another officer waitlist entry for this event'; end if;
  select * into old_entry from public.event_waitlist where event_id=p_event_id
    and officer_id=p_officer_id for update;
  if not found then return; end if;
  delete from public.event_waitlist where id=old_entry.id;
  perform private.write_audit_log('event.waitlist_left','event',p_event_id::text,
    pg_catalog.jsonb_build_object('event_id',p_event_id,'officer_id',p_officer_id,
      'waitlist_id',old_entry.id,'joined_at',old_entry.joined_at,'actor_id',actor_id));
end;
$$;

