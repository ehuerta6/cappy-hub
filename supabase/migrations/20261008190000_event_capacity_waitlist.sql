create function private.create_recurring_event_with_capacity(
  p_name text,p_description text,p_event_type_id bigint,p_location text,p_branch_ids bigint[],
  p_slides_url text,p_meeting_notes_url text,p_signup_sheet_url text,p_max_volunteers integer,
  p_request_key uuid,p_recurrence_rule text,p_event_dates date[],p_starts_at timestamptz[],p_ends_at timestamptz[]
) returns bigint language plpgsql security definer set search_path = '' as $$
declare first_id bigint; series_id bigint; prior_limit integer; prior_event_id bigint; had_receipt boolean;
begin
  if p_max_volunteers<0 then
    raise exception 'Max volunteers must be a positive whole number'; end if;
  perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended(p_request_key::text,73));
  select max_volunteers,first_event_id into prior_limit,prior_event_id from private.recurring_event_capacity_requests
    where request_key=p_request_key for update;
  had_receipt := found;
  if had_receipt then
    if prior_limit is distinct from nullif(p_max_volunteers,0) then raise exception 'Idempotency key already used'; end if;
    first_id := public.create_recurring_event(p_name,p_description,p_event_type_id,p_location,
      p_branch_ids,p_slides_url,p_meeting_notes_url,p_signup_sheet_url,p_request_key,
      p_recurrence_rule,p_event_dates,p_starts_at,p_ends_at);
    if first_id is distinct from prior_event_id then raise exception 'Idempotency key already used'; end if;
    return first_id;
  end if;
  first_id := public.create_recurring_event(p_name,p_description,p_event_type_id,p_location,
    p_branch_ids,p_slides_url,p_meeting_notes_url,p_signup_sheet_url,p_request_key,
    p_recurrence_rule,p_event_dates,p_starts_at,p_ends_at);
  select recurrence_series_id into series_id from public.events where id=first_id;
  insert into private.recurring_event_capacity_requests(request_key,first_event_id,max_volunteers)
    values(p_request_key,first_id,nullif(p_max_volunteers,0));
  for first_id in select id from public.events where recurrence_series_id=series_id order by recurrence_key loop
    perform private.set_event_capacity(first_id,nullif(p_max_volunteers,0));
  end loop;
  select id into first_id from public.events where recurrence_series_id=series_id
    order by recurrence_key limit 1;
  return first_id;
end;
$$;

