create function public.save_event(p_name text,p_description text,p_type text,p_location text,p_starts_at timestamptz,p_ends_at timestamptz,p_branch_ids bigint[],p_event_id bigint default null)
returns bigint language plpgsql security invoker set search_path='' as $$
declare saved_id bigint; current_event public.events;
begin
 if coalesce(cardinality(p_branch_ids),0)=0 then raise exception 'Select at least one branch'; end if;
 if p_event_id is null then
  insert into public.events(name,description,type,location,starts_at,ends_at) values(trim(p_name),p_description,trim(p_type),nullif(trim(p_location),''),p_starts_at,p_ends_at) returning id into saved_id;
 else
  select * into current_event from public.events where id=p_event_id for update;
  if not found then raise exception 'Event not found'; end if;
  if current_event.starts_at<=now() or current_event.status='cancelled' then raise exception 'Only upcoming events can be edited'; end if;
  update public.events set name=trim(p_name),description=p_description,type=trim(p_type),location=nullif(trim(p_location),''),starts_at=p_starts_at,ends_at=p_ends_at where id=p_event_id returning id into saved_id;
 end if;
 delete from public.event_branches where event_id=saved_id;
 insert into public.event_branches(event_id,branch_id) select saved_id,branch_id from unnest(p_branch_ids) as branch_id;
 return saved_id;
end; $$;
create function public.change_event_signup(p_event_id bigint,p_officer_id bigint,p_remove boolean default false)
returns void language plpgsql security invoker set search_path='' as $$
declare current_event public.events;
begin
 select * into current_event from public.events where id=p_event_id for update;
 if not found then raise exception 'Event not found'; end if;
 if current_event.ends_at<=now() or current_event.status='cancelled' then raise exception 'Signups are closed for this event'; end if;
 if p_remove then delete from public.event_officers where event_id=p_event_id and officer_id=p_officer_id;
 else insert into public.event_officers(event_id,officer_id) values(p_event_id,p_officer_id) on conflict do nothing; end if;
end; $$;
revoke all on function public.save_event(text,text,text,text,timestamptz,timestamptz,bigint[],bigint) from public;
revoke all on function public.change_event_signup(bigint,bigint,boolean) from public;
grant execute on function public.save_event(text,text,text,text,timestamptz,timestamptz,bigint[],bigint),public.change_event_signup(bigint,bigint,boolean) to anon;
