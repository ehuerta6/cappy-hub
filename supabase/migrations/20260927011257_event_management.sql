create table public.events (
 id bigint generated by default as identity primary key,
 name text not null check(length(trim(name))>0),
 description text not null default '', type text not null check(length(trim(type))>0),
 location text, starts_at timestamptz not null, ends_at timestamptz not null,
 status text not null default 'upcoming' check(status in ('upcoming','happening','past','cancelled')),
 created_at timestamptz not null default now(), check(ends_at>starts_at)
);
create table public.event_branches (
 event_id bigint not null references public.events(id), branch_id bigint not null references public.branches(id),
 primary key(event_id,branch_id)
);
create table public.event_officers (
 event_id bigint not null references public.events(id), officer_id bigint not null references public.officers(id),
 primary key(event_id,officer_id)
);
create index event_branches_branch_id_idx on public.event_branches(branch_id);
create index event_officers_officer_id_idx on public.event_officers(officer_id);
create index events_starts_at_idx on public.events(starts_at);
