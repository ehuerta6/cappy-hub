-- Capture the original hand-created schema so a new database can replay this migration.
create table if not exists public.officers (
  id bigint generated by default as identity primary key,
  name text not null,
  email text not null unique,
  position text not null,
  classification text not null check (classification in ('freshman','sophomore','junior','senior','masters','phd')),
  status text not null default 'active' check (status in ('active','inactive')),
  created_at timestamptz not null default now()
);
create table if not exists public.branches (
  id bigint generated by default as identity primary key,
  name text not null unique,
  created_at timestamptz not null default now()
);
create table if not exists public.officer_branches (
  officer_id bigint not null references public.officers(id),
  branch_id bigint not null references public.branches(id),
  primary key (officer_id, branch_id)
);
insert into public.branches (name) values ('intro'),('social'),('icpc'),('general') on conflict (name) do nothing;

create table public.positions (
  id bigint generated by default as identity primary key,
  name text not null unique check (length(trim(name)) > 0),
  can_manage_branch_events boolean not null default false,
  created_at timestamptz not null default now()
);
