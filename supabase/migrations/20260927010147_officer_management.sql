-- One database transaction prevents saving an officer without their selected memberships.
create function public.save_officer(
  p_name text, p_email text, p_position_id bigint, p_classification text, p_status text,
  p_branch_ids bigint[], p_officer_id bigint default null
) returns bigint language plpgsql security invoker set search_path = '' as $$
declare saved_id bigint;
begin
  if p_email !~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$' then
    raise exception 'Enter a valid email address';
  end if;
  if p_officer_id is null then
    insert into public.officers (name,email,position_id,classification,status)
    values (trim(p_name),lower(trim(p_email)),p_position_id,p_classification,p_status)
    returning id into saved_id;
  else
    update public.officers set name=trim(p_name),email=lower(trim(p_email)),position_id=p_position_id,
      classification=p_classification,status=p_status where id=p_officer_id returning id into saved_id;
    if saved_id is null then raise exception 'Officer not found'; end if;
  end if;
  delete from public.officer_branches where officer_id=saved_id;
  insert into public.officer_branches (officer_id,branch_id)
  select saved_id, branch_id from unnest(p_branch_ids) as branch_id;
  return saved_id;
end;
$$;
revoke all on function public.save_officer(text,text,bigint,text,text,bigint[],bigint) from public;
grant execute on function public.save_officer(text,text,bigint,text,text,bigint[],bigint) to anon;
