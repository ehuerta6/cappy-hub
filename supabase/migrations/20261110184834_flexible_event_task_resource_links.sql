-- Resource links are occurrence/task-owned children. Parent hard deletion may
-- remove these rows, while removing one row never reaches its parent.
create table public.resource_links (
  id bigint generated by default as identity primary key,
  event_id bigint references public.events(id) on delete cascade,
  task_id bigint references public.tasks(id) on delete cascade,
  kind text not null check (kind in ('slides','meeting_notes','signup_sheet','documentation','custom')),
  label text not null check (label=pg_catalog.btrim(label) and char_length(label) between 1 and 80),
  url text not null,
  sort_order integer not null default 0 check (sort_order >= 0),
  legacy_key text check (legacy_key in ('slides','meeting_notes','signup_sheet')),
  constraint resource_links_one_owner check ((event_id is null) <> (task_id is null)),
  constraint resource_links_fixed_label check (
    (kind='slides' and label='Slides') or
    (kind='meeting_notes' and label='Meeting notes') or
    (kind='signup_sheet' and label='Signup sheet') or
    (kind='documentation' and label='Documentation') or kind='custom'
  ),
  constraint resource_links_event_legacy_kind check (
    event_id is null or legacy_key is null or kind=legacy_key
  ),
  constraint resource_links_task_no_legacy check (task_id is null or legacy_key is null),
  constraint resource_links_valid_url check (
    char_length(url)>=1 and (legacy_key is not null or char_length(url)<=2048)
    and url ~* '^https?://[^[:space:]]+$'
  )
);

create index resource_links_event_order_idx on public.resource_links(event_id,sort_order,id)
  where event_id is not null;
create index resource_links_task_order_idx on public.resource_links(task_id,sort_order,id)
  where task_id is not null;
create unique index resource_links_event_legacy_key_idx on public.resource_links(event_id,legacy_key)
;

alter table public.resource_links enable row level security;
revoke all on public.resource_links from public,anon,authenticated;
grant select on public.resource_links to authenticated;

-- Parent RLS determines who may read the resource. Writes are exposed only
-- through the trusted domain mutation RPCs added below.
create policy "Approved officers read resources for visible Events and Tasks"
on public.resource_links for select to authenticated
using (
  (event_id is not null and exists(select 1 from public.events e where e.id=event_id))
  or (task_id is not null and exists(select 1 from public.tasks t where t.id=task_id))
);

-- Keep every current legacy Event link readable. The marker makes this copy
-- idempotent and lets old RPC callers update only the compatibility row.
insert into public.resource_links(event_id,kind,label,url,sort_order,legacy_key)
select e.id,legacy.kind,legacy.label,pg_catalog.btrim(legacy.url),legacy.sort_order,legacy.kind
from public.events e
cross join lateral (values
  ('slides'::text,'Slides'::text,e.slides_url,1),
  ('meeting_notes'::text,'Meeting notes'::text,e.meeting_notes_url,2),
  ('signup_sheet'::text,'Signup sheet'::text,e.signup_sheet_url,3)
) as legacy(kind,label,url,sort_order)
where nullif(pg_catalog.btrim(legacy.url),'') is not null
on conflict (event_id,legacy_key)
do update set kind=excluded.kind,label=excluded.label,url=excluded.url,sort_order=excluded.sort_order;

create function private.sync_event_legacy_resource_links()
returns trigger language plpgsql security definer set search_path = '' as $$
declare legacy record;
begin
  for legacy in select * from (values
    ('slides'::text,'Slides'::text,new.slides_url,1),
    ('meeting_notes'::text,'Meeting notes'::text,new.meeting_notes_url,2),
      ('signup_sheet'::text,'Signup sheet'::text,new.signup_sheet_url,3)
  ) as links(kind,label,url,sort_order)
  loop
    if tg_op='INSERT' or (tg_op='UPDATE' and
      case legacy.kind
        when 'slides' then old.slides_url is distinct from new.slides_url
        when 'meeting_notes' then old.meeting_notes_url is distinct from new.meeting_notes_url
        else old.signup_sheet_url is distinct from new.signup_sheet_url
      end) then
      if nullif(pg_catalog.btrim(legacy.url),'') is null then
        delete from public.resource_links where event_id=new.id and legacy_key=legacy.kind;
      else
        insert into public.resource_links(event_id,kind,label,url,sort_order,legacy_key)
        values(new.id,legacy.kind,legacy.label,pg_catalog.btrim(legacy.url),legacy.sort_order,legacy.kind)
        on conflict (event_id,legacy_key)
        do update set kind=excluded.kind,label=excluded.label,url=excluded.url;
      end if;
    end if;
  end loop;
  return new;
end;
$$;

revoke all on function private.sync_event_legacy_resource_links()
  from public,anon,authenticated;
create trigger events_sync_legacy_resource_links
after insert or update of slides_url,meeting_notes_url,signup_sheet_url on public.events
for each row execute function private.sync_event_legacy_resource_links();

create function private.assert_resource_links(p_resources jsonb,p_allow_legacy boolean)
returns void language plpgsql set search_path = '' as $$
begin
  if p_resources is null or jsonb_typeof(p_resources)<>'array' then
    raise exception 'Resource links must be an array'; end if;
  if exists (
    select 1 from jsonb_array_elements(p_resources) item
    where jsonb_typeof(item)<>'object'
      or exists(select 1 from jsonb_object_keys(item) k
        where k not in ('kind','label','url','legacy_key'))
      or item->>'kind' not in ('slides','meeting_notes','signup_sheet','documentation','custom')
      or nullif(pg_catalog.btrim(item->>'label'),'') is null
      or char_length(pg_catalog.btrim(item->>'label'))>80
      or item->>'label' is distinct from case item->>'kind'
        when 'slides' then 'Slides'
        when 'meeting_notes' then 'Meeting notes'
        when 'signup_sheet' then 'Signup sheet'
        when 'documentation' then 'Documentation'
        else pg_catalog.btrim(item->>'label') end
      or nullif(pg_catalog.btrim(item->>'url'),'') is null
      or (item->>'legacy_key' is null and char_length(pg_catalog.btrim(item->>'url'))>2048)
      or pg_catalog.btrim(item->>'url') !~* '^https?://[^[:space:]]+$'
      or (item->>'legacy_key' is not null and not p_allow_legacy)
      or (item->>'legacy_key' is not null and item->>'legacy_key' not in ('slides','meeting_notes','signup_sheet'))
      or (item->>'legacy_key' is not null and item->>'legacy_key' is distinct from item->>'kind')
  ) then raise exception 'Invalid resource link'; end if;
  if exists(
    select item->>'legacy_key' from jsonb_array_elements(p_resources) item
    where item->>'legacy_key' is not null group by item->>'legacy_key' having count(*)>1
  ) then raise exception 'Only one existing legacy link may be edited for each type'; end if;
end;
$$;

create function private.replace_event_resource_links(p_event_ids bigint[],p_resources jsonb)
returns void language plpgsql security definer set search_path = '' as $$
declare event_key bigint; before_links jsonb; after_links jsonb;
begin
  if private.current_active_officer_id() is null then raise exception 'Unauthorized'; end if;
  perform private.assert_resource_links(p_resources,true);
  if p_event_ids is null or cardinality(p_event_ids)=0 or
    cardinality(p_event_ids)<>(select count(distinct id) from unnest(p_event_ids) id) then
    raise exception 'Invalid Event resource scope'; end if;
  for event_key in select unnest(p_event_ids) order by 1 loop
    perform 1 from public.events e where e.id=event_key for update;
    if not found then raise exception 'Event not found'; end if;
    if not private.can_manage_event(event_key) then raise exception 'Event outside branch scope'; end if;
    if exists(select 1 from public.events e where e.id=event_key and e.deleted_at is not null) then
      raise exception 'This Event cannot be edited'; end if;
    select coalesce(jsonb_agg(jsonb_build_object(
      'kind',kind,'label',label,'url',url,'legacy_key',legacy_key)
      order by sort_order,id),'[]'::jsonb) into before_links
    from public.resource_links where event_id=event_key;
    delete from public.resource_links where event_id=event_key;
    insert into public.resource_links(event_id,kind,label,url,sort_order,legacy_key)
    select event_key,item->>'kind',item->>'label',pg_catalog.btrim(item->>'url'),
      (row_number() over(order by ordinal))::integer-1,nullif(item->>'legacy_key','')
    from jsonb_array_elements(p_resources) with ordinality as entries(item,ordinal);
    -- Legacy columns remain a compatibility projection. The trigger only
    -- touches rows carrying the corresponding legacy_key.
    update public.events e set
      slides_url=(select r.url from public.resource_links r where r.event_id=event_key and r.legacy_key='slides'),
      meeting_notes_url=(select r.url from public.resource_links r where r.event_id=event_key and r.legacy_key='meeting_notes'),
      signup_sheet_url=(select r.url from public.resource_links r where r.event_id=event_key and r.legacy_key='signup_sheet')
    where e.id=event_key;
    select coalesce(jsonb_agg(jsonb_build_object(
      'kind',kind,'label',label,'url',url,'legacy_key',legacy_key)
      order by sort_order,id),'[]'::jsonb) into after_links
    from public.resource_links where event_id=event_key;
    if before_links is distinct from after_links then
      perform private.write_audit_log('event.resources_updated','event',event_key::text,
        jsonb_build_object('before',before_links,'after',after_links));
    end if;
  end loop;
end;
$$;

create function private.replace_task_resource_links(p_task_ids bigint[],p_resources jsonb)
returns void language plpgsql security definer set search_path = '' as $$
declare task_key bigint; task_branch bigint; before_links jsonb; after_links jsonb;
begin
  if private.current_active_officer_id() is null then raise exception 'Unauthorized'; end if;
  perform private.assert_resource_links(p_resources,false);
  if p_task_ids is null or cardinality(p_task_ids)=0 or
    cardinality(p_task_ids)<>(select count(distinct id) from unnest(p_task_ids) id) then
    raise exception 'Invalid Task resource scope'; end if;
  for task_key in select unnest(p_task_ids) order by 1 loop
    select branch_id into task_branch from public.tasks t where t.id=task_key and t.removed_at is null for update;
    if not found then raise exception 'Task not found'; end if;
    if not private.can_manage_branches(array[task_branch]) then raise exception 'Task outside branch scope'; end if;
    select coalesce(jsonb_agg(jsonb_build_object(
      'kind',kind,'label',label,'url',url,'legacy_key',legacy_key)
      order by sort_order,id),'[]'::jsonb) into before_links
    from public.resource_links where task_id=task_key;
    delete from public.resource_links where task_id=task_key;
    insert into public.resource_links(task_id,kind,label,url,sort_order,legacy_key)
    select task_key,item->>'kind',item->>'label',pg_catalog.btrim(item->>'url'),
      (row_number() over(order by ordinal))::integer-1,null
    from jsonb_array_elements(p_resources) with ordinality as entries(item,ordinal);
    select coalesce(jsonb_agg(jsonb_build_object(
      'kind',kind,'label',label,'url',url,'legacy_key',legacy_key)
      order by sort_order,id),'[]'::jsonb) into after_links
    from public.resource_links where task_id=task_key;
    if before_links is distinct from after_links then
      perform private.write_audit_log('task.resources_updated','task',task_key::text,
        jsonb_build_object('before',before_links,'after',after_links));
    end if;
  end loop;
end;
$$;

