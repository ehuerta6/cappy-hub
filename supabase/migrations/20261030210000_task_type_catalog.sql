-- Replace the fixed list with catalog validation. Reconciliation and Task
-- identity behavior remain in the existing trusted Task functions.
create or replace function private.save_task(
  p_title text, p_description text, p_task_type text, p_branch_id bigint,
  p_due_date date, p_points numeric, p_approval_required boolean
) returns bigint language plpgsql security definer set search_path = '' as $$
declare saved_id bigint; actor_id bigint := private.current_active_officer_id();
begin
  if actor_id is null then raise exception 'Unauthorized'; end if;
  if not private.can_manage_branches(array[p_branch_id]) then
    raise exception 'Task outside branch scope'; end if;
  if exists(select 1 from public.branches where id = p_branch_id and not is_active) then
    raise exception 'Invalid or retired branch'; end if;
  if nullif(pg_catalog.btrim(p_title), '') is null or
      nullif(pg_catalog.btrim(p_description), '') is null or p_due_date is null or
      p_task_type is null or not exists (select 1 from public.task_types
        where name = p_task_type and available_for_new_tasks) or
      p_points is null or p_points <= 0 or
      p_points in ('NaN'::numeric, 'Infinity'::numeric, '-Infinity'::numeric) or
      p_approval_required is null then raise exception 'Invalid task fields'; end if;
  insert into public.tasks(title, description, task_type, branch_id, due_date,
    points, approval_required, created_by)
    values(pg_catalog.btrim(p_title), pg_catalog.btrim(p_description), p_task_type,
      p_branch_id, p_due_date, p_points, p_approval_required, actor_id)
    returning id into saved_id;
  perform private.write_audit_log('task.created', 'task', saved_id::text,
    pg_catalog.jsonb_build_object('task_type', p_task_type, 'branch_id', p_branch_id,
      'points', p_points, 'approval_required', p_approval_required));
  return saved_id;
end;
$$;

create or replace function private.update_task_details(
  p_task_id bigint, p_title text, p_description text, p_task_type text,
  p_branch_id bigint, p_due_date date, p_points numeric
) returns void language plpgsql security definer set search_path = '' as $$
declare task_row public.tasks%rowtype; actor_id bigint := private.current_active_officer_id();
begin
  if actor_id is null then raise exception 'Unauthorized'; end if;
  select * into task_row from public.tasks where id = p_task_id for update;
  if not found then raise exception 'Task not found'; end if;
  if task_row.removed_at is not null then raise exception 'Task has been removed'; end if;
  if not private.can_manage_branches(array[task_row.branch_id]) or
      not private.can_manage_branches(array[p_branch_id]) then
    raise exception 'Task outside branch scope'; end if;
  if exists(select 1 from public.branches where id = p_branch_id and not is_active
      and id <> task_row.branch_id) then raise exception 'Invalid or retired branch'; end if;
  if nullif(pg_catalog.btrim(p_title), '') is null or
      nullif(pg_catalog.btrim(p_description), '') is null or p_task_type is null or
      (p_task_type is distinct from task_row.task_type and not exists (
        select 1 from public.task_types where name = p_task_type and available_for_new_tasks)) or
      p_due_date is null or p_points is null or p_points <= 0 or
      p_points in ('NaN'::numeric, 'Infinity'::numeric, '-Infinity'::numeric) then
    raise exception 'Invalid task fields'; end if;
  update public.tasks set title = pg_catalog.btrim(p_title),
    description = pg_catalog.btrim(p_description), task_type = p_task_type,
    branch_id = p_branch_id, due_date = p_due_date, points = p_points
    where id = p_task_id;
  perform private.write_audit_log('task.updated', 'task', p_task_id::text,
    pg_catalog.jsonb_build_object('before', pg_catalog.to_jsonb(task_row),
      'after', (select pg_catalog.to_jsonb(t) from public.tasks t where id = p_task_id)));
end;
$$;
