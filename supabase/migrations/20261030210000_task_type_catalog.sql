-- Task types remain text on Tasks; the catalog makes new choices manageable
-- without adding a second identifier to existing Task rows.
create table public.task_types (
  id bigint generated by default as identity primary key,
  name text not null unique,
  available_for_new_tasks boolean not null default true,
  constraint task_types_name_not_blank check (name ~ '[^[:space:]]')
);

create unique index task_types_normalized_name_key on public.task_types
  (pg_catalog.lower(pg_catalog.regexp_replace(
    pg_catalog.regexp_replace(name, '^[[:space:]]+|[[:space:]]+$', '', 'g'),
    '[[:space:]]+', ' ', 'g')));

-- Keep any pre-existing value readable. Only the current five values become
-- available by default; an unexpected historical value stays retired.
insert into public.task_types(name, available_for_new_tasks)
select values_to_keep.name,
  values_to_keep.name in ('Flyer', 'LinkedIn', 'Airtable', 'Story', 'Post')
from (
  select distinct task_type as name from public.tasks
  union
  select unnest(array['Flyer', 'LinkedIn', 'Airtable', 'Story', 'Post']::text[])
) values_to_keep
on conflict do nothing;

alter table public.tasks drop constraint tasks_task_type_check;
alter table public.tasks add constraint tasks_task_type_fkey
  foreign key (task_type) references public.task_types(name)
  on update cascade on delete restrict not valid;
alter table public.tasks validate constraint tasks_task_type_fkey;

alter table public.task_types enable row level security;
revoke all on public.task_types from public, anon, authenticated;
grant select on public.task_types to authenticated;
create policy "Active Officers read Task Types" on public.task_types
  for select to authenticated
  using ((select private.current_active_officer_id()) is not null);

-- All Task writes use trusted functions. This also covers recurrence edits,
-- which update existing occurrence rows directly inside their trusted RPC.
create function private.validate_task_type_choice() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  if tg_op = 'UPDATE' and new.task_type is not distinct from old.task_type then
    return new;
  end if;
  if not exists (select 1 from public.task_types
      where name = new.task_type and available_for_new_tasks) then
    raise exception 'Invalid or unavailable Task type';
  end if;
  return new;
end;
$$;
revoke all on function private.validate_task_type_choice() from public, anon, authenticated;
create trigger validate_task_type_choice
  before insert or update of task_type on public.tasks
  for each row execute function private.validate_task_type_choice();

create function private.create_task_type(p_name text) returns bigint
language plpgsql security definer set search_path = '' as $$
declare saved_id bigint; normalized_name text;
begin
  if not private.current_is_admin() then raise exception 'Admin required'; end if;
  if p_name is null or p_name !~ '[^[:space:]]' then
    raise exception 'Task type name is required';
  end if;
  normalized_name := pg_catalog.btrim(p_name);
  insert into public.task_types(name, available_for_new_tasks)
    values (normalized_name, true) returning id into saved_id;
  perform private.write_audit_log('task_type.created', 'task_type', saved_id::text,
    pg_catalog.jsonb_build_object('name', normalized_name));
  return saved_id;
end;
$$;

create function private.rename_task_type(p_id bigint, p_name text) returns void
language plpgsql security definer set search_path = '' as $$
declare old_row public.task_types; normalized_name text; task_count bigint;
begin
  if not private.current_is_admin() then raise exception 'Admin required'; end if;
  if p_name is null or p_name !~ '[^[:space:]]' then
    raise exception 'Task type name is required';
  end if;
  normalized_name := pg_catalog.btrim(p_name);
  select * into old_row from public.task_types where id = p_id for update;
  if not found then raise exception 'Task type not found'; end if;
  if old_row.name = normalized_name then
    return;
  end if;
  select count(*) into task_count from public.tasks where task_type = old_row.name;
  -- The temporary active value lets the Task guard accept the FK cascade. It
  -- is all within this transaction; the original availability is restored.
  update public.task_types set name = normalized_name, available_for_new_tasks = true
    where id = p_id;
  if not old_row.available_for_new_tasks then
    update public.task_types set available_for_new_tasks = false where id = p_id;
  end if;
  perform private.write_audit_log('task_type.renamed', 'task_type', p_id::text,
    pg_catalog.jsonb_build_object('before', pg_catalog.to_jsonb(old_row),
      'after', (select pg_catalog.to_jsonb(t) from public.task_types t where id = p_id),
      'affected_task_count', task_count));
end;
$$;

create function private.delete_task_type(p_id bigint) returns void
language plpgsql security definer set search_path = '' as $$
declare old_row public.task_types;
begin
  if not private.current_is_admin() then raise exception 'Admin required'; end if;
  select * into old_row from public.task_types where id = p_id for update;
  if not found then raise exception 'Task type not found'; end if;
  if old_row.available_for_new_tasks then
    update public.task_types set available_for_new_tasks = false where id = p_id;
    perform private.write_audit_log('task_type.deleted', 'task_type', p_id::text,
      pg_catalog.jsonb_build_object('before', pg_catalog.to_jsonb(old_row),
        'after', (select pg_catalog.to_jsonb(t) from public.task_types t where id = p_id)));
  end if;
end;
$$;

create function private.restore_task_type(p_id bigint) returns void
language plpgsql security definer set search_path = '' as $$
declare old_row public.task_types;
begin
  if not private.current_is_admin() then raise exception 'Admin required'; end if;
  select * into old_row from public.task_types where id = p_id for update;
  if not found then raise exception 'Task type not found'; end if;
  if not old_row.available_for_new_tasks then
    update public.task_types set available_for_new_tasks = true where id = p_id;
    perform private.write_audit_log('task_type.restored', 'task_type', p_id::text,
      pg_catalog.jsonb_build_object('before', pg_catalog.to_jsonb(old_row),
        'after', (select pg_catalog.to_jsonb(t) from public.task_types t where id = p_id)));
  end if;
end;
$$;

create function public.create_task_type(p_name text) returns bigint
language sql security invoker set search_path = '' as $$
  select private.create_task_type(p_name)
$$;
create function public.rename_task_type(p_id bigint, p_name text) returns void
language sql security invoker set search_path = '' as $$
  select private.rename_task_type(p_id, p_name)
$$;
create function public.delete_task_type(p_id bigint) returns void
language sql security invoker set search_path = '' as $$
  select private.delete_task_type(p_id)
$$;
create function public.restore_task_type(p_id bigint) returns void
language sql security invoker set search_path = '' as $$
  select private.restore_task_type(p_id)
$$;
revoke all on function private.create_task_type(text), private.rename_task_type(bigint, text),
  private.delete_task_type(bigint), private.restore_task_type(bigint),
  public.create_task_type(text), public.rename_task_type(bigint, text),
  public.delete_task_type(bigint), public.restore_task_type(bigint)
