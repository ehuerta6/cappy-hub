create table public.academic_periods (
  id bigint generated by default as identity primary key,
  name text not null check (pg_catalog.length(pg_catalog.btrim(name)) > 0),
  starts_on date not null,
  ends_on date not null,
  created_at timestamptz not null default pg_catalog.now(),
  updated_at timestamptz not null default pg_catalog.now(),
  check (ends_on >= starts_on),
  constraint academic_periods_no_overlap exclude using gist
    (daterange(starts_on, ends_on, '[]') with &&)
);

create index academic_periods_starts_on_idx
  on public.academic_periods (starts_on desc, id desc);

alter table public.academic_periods enable row level security;
create policy "authenticated users can read academic periods"
  on public.academic_periods for select to authenticated using (true);
revoke all on public.academic_periods from public, anon, authenticated;
grant select on public.academic_periods to authenticated;

create or replace function private.save_academic_period(
  p_name text, p_starts_on date, p_ends_on date, p_period_id bigint default null
) returns bigint language plpgsql security definer set search_path = '' as $$
declare saved_id bigint; old_period public.academic_periods;
begin
  if not private.current_is_admin() then raise exception 'Admin required'; end if;
  if nullif(pg_catalog.btrim(p_name), '') is null then raise exception 'Period name required'; end if;
  if p_starts_on is null or p_ends_on is null or p_ends_on < p_starts_on then
    raise exception 'Period dates are invalid';
  end if;
  if p_period_id is null then
    insert into public.academic_periods(name, starts_on, ends_on)
    values (pg_catalog.btrim(p_name), p_starts_on, p_ends_on)
    returning id into saved_id;
    perform private.write_audit_log('academic_period.created', 'academic_period', saved_id::text,
      pg_catalog.jsonb_build_object('after', (select pg_catalog.to_jsonb(p) from public.academic_periods p where id=saved_id)));
  else
    select * into old_period from public.academic_periods where id=p_period_id for update;
    if not found then raise exception 'Academic period not found'; end if;
    update public.academic_periods
      set name=pg_catalog.btrim(p_name), starts_on=p_starts_on, ends_on=p_ends_on,
          updated_at=pg_catalog.now()
      where id=p_period_id returning id into saved_id;
    if old_period.name is distinct from pg_catalog.btrim(p_name)
      or old_period.starts_on is distinct from p_starts_on
      or old_period.ends_on is distinct from p_ends_on then
      perform private.write_audit_log('academic_period.updated', 'academic_period', saved_id::text,
        pg_catalog.jsonb_build_object('before', pg_catalog.to_jsonb(old_period),
          'after', (select pg_catalog.to_jsonb(p) from public.academic_periods p where id=saved_id)));
    end if;
  end if;
  return saved_id;
end;
$$;

create function public.save_academic_period(
  p_name text, p_starts_on date, p_ends_on date, p_period_id bigint default null
) returns bigint language sql security invoker set search_path = '' as $$
  select private.save_academic_period(p_name, p_starts_on, p_ends_on, p_period_id)
$$;
revoke all on function private.save_academic_period(text,date,date,bigint),
  public.save_academic_period(text,date,date,bigint) from public, anon, authenticated;
grant execute on function private.save_academic_period(text,date,date,bigint) to authenticated;
grant execute on function public.save_academic_period(text,date,date,bigint) to authenticated;

create or replace function public.academic_period_context()
returns table(current_date_denver date, current_period_id bigint)
language sql stable security invoker set search_path = '' as $$
  select d.local_date, p.id
  from (select (pg_catalog.statement_timestamp() at time zone 'America/Denver')::date as local_date) d
  left join public.academic_periods p on d.local_date between p.starts_on and p.ends_on
$$;
revoke all on function public.academic_period_context() from public, anon;
grant execute on function public.academic_period_context() to authenticated;

create or replace function public.assert_academic_period_writable(p_period_id bigint)
returns void language plpgsql security invoker set search_path = '' as $$
declare today date := (pg_catalog.statement_timestamp() at time zone 'America/Denver')::date;
begin
  if p_period_id is null then return; end if;
  if exists(select 1 from public.academic_periods p
    where p.id=p_period_id and p.ends_on < today) then
    raise exception 'Historical period is read-only';
  end if;
  if not exists(select 1 from public.academic_periods p where p.id=p_period_id) then
    raise exception 'Academic period not found';
  end if;
end;
$$;
revoke all on function public.assert_academic_period_writable(bigint) from public, anon;
grant execute on function public.assert_academic_period_writable(bigint) to authenticated;

create or replace view public.point_history with (security_invoker=true) as
  select p.id,p.officer_id,p.event_id,p.points,p.reason,p.award_type,
    p.created_by,p.created_at,p.removed_at,p.removed_by,p.updated_at,p.updated_by,p.task_id,
    o.name as officer_name,e.name as event_name,
    creator.name as created_by_name,remover.name as removed_by_name,
    t.title as task_title,
    pg_catalog.concat_ws(' ',o.name,p.reason,e.name,t.title) as search_text,
    e.event_date as event_date,
    case
      when e.id is not null then e.event_date
      when t.id is not null then t.due_date
      else (p.created_at at time zone 'America/Denver')::date
    end as activity_date,
    p.created_by_officer_id,p.updated_by_officer_id,p.removed_by_officer_id,
    updater.name as updated_by_name,p.participation_superseded_at,
    p.participation_schedule_suspended,
    (p.removed_at is not null and not p.slot_selection_removed and p.award_type='participation'
      and p.participation_superseded_at is null
      and (p.removed_by is not null or p.removed_by_officer_id is not null)) as premature_confirmation_available
  from public.point_transactions p
  join public.officers o on o.id=p.officer_id
  left join public.events e on e.id=p.event_id
  left join public.tasks t on t.id=p.task_id
  left join public.officers creator on creator.id=p.created_by_officer_id
    or (p.created_by_officer_id is null and creator.auth_user_id=p.created_by)
  left join public.officers remover on remover.id=p.removed_by_officer_id
    or (p.removed_by_officer_id is null and remover.auth_user_id=p.removed_by)
  left join public.officers updater on updater.id=p.updated_by_officer_id
    or (p.updated_by_officer_id is null and updater.auth_user_id=p.updated_by);
